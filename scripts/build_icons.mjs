function innerSvg(file) {
  const svg = readFileSync(join(HERO, `${file}.svg`), 'utf8');
  const inner = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .trim();
  return inner.replace(/\s+/g, ' ').replace(/> </g, '><');
}

